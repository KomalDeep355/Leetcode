class Solution:
    def moveZeroes(self, nums: List[int]) -> None:
        """
        Do not return anything, modify nums in-place instead.
        """
        n = len(nums)
        count = 0
        for i in nums:
            if i == 0:
                count +=1
        non_zero = [num for num in nums if num != 0]
        nums[:] = non_zero + [0] * count
        return nums

